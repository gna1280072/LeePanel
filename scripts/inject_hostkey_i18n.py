def main():
    for lang in LANGS:
        path = os.path.join(BASE, lang + ".json")
        with io.open(path, encoding="utf-8") as f:
            data = json.load(f)
        data["hostKey"] = HOST_KEY[lang]
        data["errorDialog"].update(ERROR_DLG[lang])
        data["sidebar"]["hostKeys"] = SIDEBAR[lang]
        with io.open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("updated", lang)


