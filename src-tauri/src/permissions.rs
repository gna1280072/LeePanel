//! 权限模型 v8 辅助模块：
//! - sudoers 白名单配置生成器（auth_mode='sudo' 的最小命令集）
//! - 命令参数校验工具（防注入：数字/域名/服务名/容器名等白名单匹配）

/// 生成 `/etc/sudoers.d/leepanel` 内容。
/// 用户以 auth_mode='sudo' 的账号执行时，仅放行以下固定命令集。
/// 部署方式：以 root 运行 `visudo -c -f <file>` 校验后复制到 /etc/sudoers.d/leepanel。
pub fn sudoers_config(username: &str) -> String {
    // 只读/查询类（各模块状态读取）
    let read_cmds = [
        "/usr/bin/systemctl status",
        "/usr/bin/systemctl list-units",
        "/usr/bin/docker ps",
        "/usr/bin/docker images",
        "/usr/bin/docker inspect",
        "/usr/bin/docker network ls",
        "/usr/bin/ss -tlnp",
        "/usr/bin/netstat -tlnp",
        "/usr/bin/ss -tnlp",
        "/usr/bin/netstat -tnlp",
        "/usr/bin/lsof",
        "/usr/bin/ps",
        "/usr/bin/df",
        "/usr/bin/free",
        "/usr/bin/uptime",
        "/usr/bin/cat",
        "/usr/bin/tail",
        "/usr/bin/nginx -t",
        "/usr/bin/php-fpm -t",
        "/usr/sbin/nginx -t",
        "/usr/sbin/php-fpm -t",
    ];
    // 管理/破坏性类（各模块写操作）
    let admin_cmds = [
        "/usr/bin/systemctl start",
        "/usr/bin/systemctl stop",
        "/usr/bin/systemctl restart",
        "/usr/bin/systemctl reload",
        "/usr/bin/systemctl enable",
        "/usr/bin/systemctl disable",
        "/usr/bin/docker start",
        "/usr/bin/docker stop",
        "/usr/bin/docker restart",
        "/usr/bin/docker rm",
        "/usr/bin/docker rmi",
        "/usr/bin/docker pull",
        "/usr/bin/docker build",
        "/usr/bin/docker network create",
        "/usr/bin/docker network rm",
        "/usr/bin/kill",
        "/usr/bin/pkill",
        "/usr/bin/reboot",
        "/usr/bin/ufw allow",
        "/usr/bin/ufw deny",
        "/usr/bin/ufw delete",
        "/usr/bin/firewall-cmd",
        "/usr/bin/iptables",
        "/usr/bin/nft",
    ];
    let mut out = String::new();
    out.push_str("# LeePanel sudo whitelist — generated by LeePanel\n");
    out.push_str("# Validate with: sudo visudo -c -f /tmp/leepanel\n");
    out.push_str("# Deploy with:   sudo install -m 440 -o root -g root /tmp/leepanel /etc/sudoers.d/leepanel\n");
    out.push_str(&format!("{} ALL=(root) NOPASSWD: ", username));
    let all: Vec<&str> = read_cmds.iter().chain(admin_cmds.iter()).copied().collect();
    out.push_str(&all.join(", "));
    out.push('\n');
    out
}

// ===== 参数校验（防注入） =====

fn reject(bad: &str, what: &str) -> Result<(), String> {
    Err(format!("Invalid {}: '{}'", what, bad))
}

/// 服务名：systemd unit 名（`[a-zA-Z0-9_.@-]+`，≤64 字符）。
pub fn validate_service_name(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 64 || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '@' | '-')) {
        return reject(s, "service name");
    }
    Ok(())
}

/// systemctl action：仅允许固定枚举。
pub fn validate_service_action(a: &str) -> Result<(), String> {
    if !matches!(a, "start" | "stop" | "restart" | "reload" | "enable" | "disable" | "status") {
        return reject(a, "service action");
    }
    Ok(())
}

/// 端口：1-65535。返回解析后的 u16。
pub fn validate_port(s: &str) -> Result<u16, String> {
    let p: u16 = s.trim().parse().map_err(|_| format!("Invalid port: '{}'", s))?;
    if p == 0 { return Err("Invalid port: must be 1-65535".to_string()); }
    Ok(p)
}

/// 协议：tcp/udp 枚举。
pub fn validate_protocol(s: &str) -> Result<(), String> {
    let l = s.to_ascii_lowercase();
    if l != "tcp" && l != "udp" { return reject(s, "protocol"); }
    Ok(())
}

/// PID：正整数。返回解析后的 u32。
pub fn validate_pid(s: &str) -> Result<u32, String> {
    let pid: u32 = s.trim().parse().map_err(|_| format!("Invalid PID: '{}'", s))?;
    if pid == 0 { return Err("Invalid PID: must be > 0".to_string()); }
    Ok(pid)
}

/// 域名 / 站点名：字母数字、点、短横线、下划线，≤253 字符，至少含一个点或可接受裸名。
pub fn validate_domain(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 253
        || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_'))
        || s.starts_with('.') || s.ends_with('.') {
        return reject(s, "domain");
    }
    Ok(())
}

/// Docker 容器/镜像名：`[a-zA-Z0-9][a-zA-Z0-9_.-]*`，≤128 字符。
pub fn validate_container_name(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 128
        || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | ':' | '/'))
        || s.starts_with('/') {
        return reject(s, "container/image name");
    }
    Ok(())
}

/// 远端路径：绝对路径、无控制字符、不含 `$()` `` ` `` `;` `&&` `||` `|` 等注入字符。
pub fn validate_path(s: &str) -> Result<(), String> {
    if s.is_empty() || !s.starts_with('/') {
        return reject(s, "path");
    }
    if s.chars().any(|c| c.is_control() || matches!(c, '$' | '`' | ';' | '&' | '|' | '<' | '>' | '\'' | '"' | '\n' | '\r')) {
        return reject(s, "path");
    }
    Ok(())
}

/// 软件包名（apt/dnf 包名）：`[a-z0-9][a-z0-9+.-]*`，≤128 字符。
pub fn validate_package_name(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 128
        || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '+' | '-' | '_')) {
        return reject(s, "package name");
    }
    Ok(())
}

/// 防火墙端口：单个端口或范围 `8080` / `8080:8090`，每段数值 1-65535。
pub fn validate_firewall_port(s: &str) -> Result<(), String> {
    let t = s.trim();
    if t.is_empty() || t.matches(':').count() > 1 {
        return reject(s, "firewall port");
    }
    for part in t.split(':') {
        let p: u16 = part.parse().map_err(|_| format!("Invalid firewall port: '{}'", s))?;
        if p == 0 { return Err("Invalid firewall port: must be 1-65535".to_string()); }
    }
    Ok(())
}

/// 防火墙协议：tcp/udp/both/any。
pub fn validate_firewall_protocol(s: &str) -> Result<(), String> {
    let l = s.to_ascii_lowercase();
    if !matches!(l.as_str(), "tcp" | "udp" | "both" | "any") {
        return reject(s, "firewall protocol");
    }
    Ok(())
}

/// 防火墙动作：allow/deny。
pub fn validate_firewall_action(s: &str) -> Result<(), String> {
    if s != "allow" && s != "deny" {
        return reject(s, "firewall action");
    }
    Ok(())
}

/// Docker 操作枚举：start/stop/restart。
pub fn validate_container_action(a: &str) -> Result<(), String> {
    if !matches!(a, "start" | "stop" | "restart") {
        return reject(a, "container action");
    }
    Ok(())
}

// ===== 软件源 / 软件安装 参数校验（GPG 校验加固） =====

/// 内部：严格 http(s) URL 校验。
/// 仅允许 `A-Za-z0-9` 与 `:/?=._-%~+,@[]`，必须以 `http://` 或 `https://` 开头。
/// 空白、引号、反引号、`$`、`;`、`&`、`|`、反斜杠一律拒绝 —— 该值可能进入 shell 上下文。
fn check_https_url(u: &str, max: usize) -> Result<(), String> {
    if u.is_empty() || u.len() > max {
        return Err("empty or too long".to_string());
    }
    if !(u.starts_with("http://") || u.starts_with("https://")) {
        return Err("must start with http:// or https://".to_string());
    }
    if !u.chars().all(|c| c.is_ascii_alphanumeric() || ":/?=._-%~+,@[]".contains(c)) {
        return Err("contains disallowed characters".to_string());
    }
    Ok(())
}

/// 软件源标识名：`[A-Za-z0-9_-]`，1-64 字符。
/// 用作 `/etc/apt/sources.list.d/<name>.list` 或 `/etc/yum.repos.d/<name>.repo` 的文件名，
/// 以及 yum repo 的 section 名（`[<name>]`）。
pub fn validate_source_name(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 64
        || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-')) {
        return reject(s, "source name");
    }
    Ok(())
}

/// GPG 公钥 URL：必须是 http(s) 且不含 shell 元字符。
pub fn validate_gpg_key_url(s: &str) -> Result<(), String> {
    check_https_url(s, 512).map_err(|_| format!("Invalid GPG key URL: '{}'", s))
}

/// 软件源定位符：完整 `deb` / `deb-src` 源行（如 `deb https://x.io/deb jammy main`），
/// 或裸 http(s) URL（由服务端补全 suite/component）。
/// 全字符集禁引号 / 反引号 / `$` / 反斜杠 / `;` / `&` / `|` / `<>`，防注入。
pub fn validate_source_locator(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 512 {
        return reject(s, "source URL");
    }
    if s.chars().any(|c| {
        c.is_control()
            || matches!(
                c,
                '\'' | '"' | '`' | '$' | '\\' | ';' | '&' | '|' | '<' | '>' | '#' | '!' | '*' | '{' | '}'
            )
    }) {
        return reject(s, "source URL");
    }
    let first = s.split_whitespace().next().unwrap_or("");
    if first == "deb" || first == "deb-src" {
        let url = s
            .split_whitespace()
            .find(|t| t.starts_with("http://") || t.starts_with("https://"))
            .ok_or_else(|| format!("Invalid source line (missing http(s) URL): '{}'", s))?;
        return check_https_url(url, 512)
            .map_err(|e| format!("Invalid source line: '{}' ({})", s, e));
    }
    check_https_url(s, 512).map_err(|e| format!("Invalid source URL: '{}' ({})", s, e))
}

/// 软件标识 / 安装目标名：字母数字开头，可含 `. + - _`，≤64 字符。
/// 覆盖内建标识（nginx/redis/php/mysql…）与 `php8.3` 形式。
pub fn validate_software_name(s: &str) -> Result<(), String> {
    if s.is_empty() || s.len() > 64 {
        return reject(s, "software name");
    }
    if !s.chars().next().map(|c| c.is_ascii_alphanumeric()).unwrap_or(false)
        || !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '+' | '-' | '_')) {
        return reject(s, "software name");
    }
    Ok(())
}

/// 软件安装动作：install / uninstall。
pub fn validate_software_action(a: &str) -> Result<(), String> {
    if !matches!(a, "install" | "uninstall") {
        return reject(a, "software action");
    }
    Ok(())
}

/// 软件安装选项：空、仓库变体（`aliyun` / `mariadb` / `mysql`）、PHP 版本（`8.2`）、
/// 源码编译模式（`source:8.3`）。仅允许 `[A-Za-z0-9.+:_-]`，≤32 字符。
pub fn validate_software_options(s: &str) -> Result<(), String> {
    if s.len() > 32 {
        return reject(s, "software options");
    }
    if !s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '+' | ':' | '-' | '_')) {
        return reject(s, "software options");
    }
    Ok(())
}

/// 展示标签净化：`display_name` 会被插值进远端 shell 的单引号内
/// （`echo '<action>:<display_name>' > /tmp/leepanel-install.info`），
/// 因此剔除控制字符与引号 / 反引号 / `$` / 反斜杠 / `;` / `&` / `|` / `<>` 等元字符，
/// 并截断至 64 字符。净化而非拒绝，避免历史自定义条目因个别字符无法安装。
pub fn sanitize_label(s: &str) -> String {
    s.chars()
        .filter(|c| {
            !c.is_control()
                && !matches!(
                    c,
                    '\'' | '"' | '`' | '$' | '\\' | ';' | '&' | '|' | '<' | '>' | '#' | '!' | '{' | '}'
                )
        })
        .take(64)
        .collect()
}

